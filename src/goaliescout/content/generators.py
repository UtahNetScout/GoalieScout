    def save_report(self, content: str, player_name: str, format_type: str = "markdown") -> str:
        """Save report to file.
        
        Args:
            content: Report content
            player_name: Player name for filename
            format_type: Format type (markdown or html)
            
        Returns:
            Path to saved file
        """
        extension = "md" if format_type == "markdown" else "html"
        safe_name = player_name.replace(" ", "_").replace("/", "_")
        filename = f"{safe_name}_report_{datetime.now().strftime('%Y%m%d')}.{extension}"
        filepath = self.output_dir / filename
        
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        
        logger.info(f"Report saved to {filepath}")
        return str(filepath)


