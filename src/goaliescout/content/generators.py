class SocialMediaManager:
    """Manage social media posts."""
    
    def __init__(self):
        """Initialize social media manager."""
        self.twitter_configured = self._check_twitter_config()
    
    def _check_twitter_config(self) -> bool:
        """Check if Twitter API credentials are configured."""
        required_keys = [
            'TWITTER_API_KEY',
            'TWITTER_API_SECRET',
            'TWITTER_ACCESS_TOKEN',
            'TWITTER_ACCESS_SECRET'
        ]
        
        return all(os.getenv(key) for key in required_keys)
    
    def create_player_tweet(self, profile_data: Dict[str, Any]) -> str:
        """Create tweet text for player spotlight.
        
        Args:
            profile_data: Goalie profile dictionary
            
        Returns:
            Tweet text (max 280 characters)
        """
        demographics = profile_data.get('demographics', {})
        name = demographics.get('name', 'Unknown')
        league = profile_data.get('league', 'Unknown')
        
        ai_analysis = profile_data.get('ai_analysis')
        
        if ai_analysis:
            rating = ai_analysis.get('overall_rating', 0)
            tweet = f"🥅 Player Spotlight: {name}\n"
            tweet += f"📊 Rating: {rating}/100\n"
            tweet += f"🏒 League: {league}\n"
            
            strengths = ai_analysis.get('strengths', [])
            if strengths:
                tweet += f"⭐ {strengths[0]}\n"
            
            tweet += "\n#HockeyScout #GoalieScouting"
        else:
            tweet = f"🥅 New goalie profile: {name} ({league})\n#HockeyScout #GoalieScouting"
        
        # Ensure tweet is within Twitter's character limit
        if len(tweet) > 280:
            tweet = tweet[:277] + "..."
        
        return tweet
    
    def post_to_twitter(self, tweet_text: str) -> bool:
        """Post tweet to Twitter/X.
        
        Args:
            tweet_text: Tweet content
            
        Returns:
            True if successful
        """
        if not self.twitter_configured:
            logger.warning("Twitter API not configured")
            return False
        
        try:
            import tweepy
            
            auth = tweepy.OAuthHandler(
                os.getenv('TWITTER_API_KEY'),
                os.getenv('TWITTER_API_SECRET')
            )
            auth.set_access_token(
                os.getenv('TWITTER_ACCESS_TOKEN'),
                os.getenv('TWITTER_ACCESS_SECRET')
            )
            
            api = tweepy.API(auth)
            api.update_status(tweet_text)
            
            logger.info("Tweet posted successfully")
            return True
            
        except Exception as e:
            logger.error(f"Error posting to Twitter: {e}")
            return False
    
    def create_ranking_tweet(self, rankings: list) -> str:
        """Create tweet for goalie rankings.
        
        Args:
            rankings: List of ranked goalies
            
        Returns:
            Tweet text
        """
        tweet = "🥅 Top Goalie Rankings 🥅\n\n"
        
        for i, goalie in enumerate(rankings[:5], 1):
            name = goalie.get('name', 'Unknown')
            tweet += f"{i}. {name}\n"
        
        tweet += "\n#HockeyScout #GoalieRankings"
        
        if len(tweet) > 280:
            tweet = tweet[:277] + "..."
        
        return tweet
