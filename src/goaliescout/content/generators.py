"""Content generation tools for scouting reports and social media."""

from typing import Dict, Any, Optional
import os
from pathlib import Path
import logging
from datetime import datetime

logger = logging.getLogger(__name__)


class ReportGenerator:
    """Generate scouting reports in various formats."""
    
    def __init__(self, output_dir: str = "./reports"):
        """Initialize report generator.
        
        Args:
            output_dir: Directory for output files
        """
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)
    
    def generate_markdown_report(self, profile_data: Dict[str, Any], ai_report: str) -> str:
        """Generate Markdown format report.
        
        Args:
            profile_data: Goalie profile dictionary
            ai_report: AI-generated report content
            
        Returns:
            Markdown formatted report
        """
        demographics = profile_data.get('demographics', {})
        league = profile_data.get('league', 'Unknown')
        
        markdown = f"""# Scouting Report: {demographics.get('name', 'Unknown')}

**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}

## Player Information

- **Name:** {demographics.get('name', 'Unknown')}
- **Country:** {demographics.get('country', 'Unknown')}
- **Date of Birth:** {demographics.get('date_of_birth', 'Unknown')}
- **Height:** {demographics.get('height', 'N/A')}
- **Weight:** {demographics.get('weight', 'N/A')}
- **Catches:** {demographics.get('catches', 'N/A')}
- **Current League:** {league}
- **Current Team:** {profile_data.get('current_team', 'N/A')}

## Performance Metrics

"""
        
        # Add performance metrics
        metrics = profile_data.get('performance_metrics', [])
        if metrics:
            markdown += "| Season | GP | W | L | SV% | GAA | SO |\n"
            markdown += "|--------|----|----|----|----|----|----||\n"
            
            for m in metrics[-5:]:  # Last 5 seasons
                markdown += f"| {m.get('season', 'N/A')} | {m.get('games_played', 0)} | {m.get('wins', 0)} | {m.get('losses', 0)} | {m.get('save_percentage', 0):.3f} | {m.get('goals_against_average', 0):.2f} | {m.get('shutouts', 0)} |\n"
        else:
            markdown += "*No performance metrics available*\n"
        
        markdown += "\n## AI Analysis\n\n"
        
        # Add AI analysis
        ai_analysis = profile_data.get('ai_analysis')
        if ai_analysis:
            markdown += f"**Overall Rating:** {ai_analysis.get('overall_rating', 0)}/100\n\n"
            markdown += f"**Potential Rating:** {ai_analysis.get('potential_rating', 0)}/100\n\n"
            markdown += f"**NHL Readiness:** {ai_analysis.get('nhl_readiness', 'Unknown')}\n\n"
            
            strengths = ai_analysis.get('strengths', [])
            if strengths:
                markdown += "### Strengths\n\n"
                for strength in strengths:
                    markdown += f"- {strength}\n"
                markdown += "\n"
            
            weaknesses = ai_analysis.get('weaknesses', [])
            if weaknesses:
                markdown += "### Weaknesses\n\n"
                for weakness in weaknesses:
                    markdown += f"- {weakness}\n"
                markdown += "\n"
            
            markdown += f"### Scouting Notes\n\n{ai_analysis.get('scouting_notes', 'N/A')}\n\n"
        
        # Add detailed AI report
        if ai_report:
            markdown += f"## Detailed Scouting Report\n\n{ai_report}\n\n"
        
        # Add NHL comparisons
        comparisons = profile_data.get('nhl_comparisons', [])
        if comparisons:
            markdown += "## NHL Comparisons\n\n"
            for comp in comparisons:
                markdown += f"### {comp.get('comparable_player', 'Unknown')}\n"
                markdown += f"**Similarity:** {comp.get('similarity_score', 0):.1f}%\n\n"
                markdown += f"{comp.get('comparison_notes', 'N/A')}\n\n"
        
        # Add injury history
        injuries = profile_data.get('injury_history', [])
        if injuries:
            markdown += "## Injury History\n\n"
            markdown += "| Date | Type | Severity | Status |\n"
            markdown += "|------|------|----------|--------|\n"
            for injury in injuries:
                markdown += f"| {injury.get('date', 'N/A')} | {injury.get('injury_type', 'N/A')} | {injury.get('severity', 'N/A')} | {injury.get('status', 'N/A')} |\n"
            markdown += "\n"
        
        markdown += "---\n\n*Report generated by Black Ops Goalie Scouting Platform*\n"
        
        return markdown
    
